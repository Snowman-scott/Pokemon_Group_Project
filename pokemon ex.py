# Define type effectiveness
TYPE_EFFECTIVENESS = {
    "FIRE": {"FIRE": 0.5, "WATER": 0.5, "GRASS": 2, "ELECTRIC": 1},
    "WATER": {"FIRE": 2, "WATER": 0.5, "GRASS": 0.5, "ELECTRIC": 0.5},
    "GRASS": {"FIRE": 0.5, "WATER": 2, "GRASS": 0.5, "ELECTRIC": 1},
    "ELECTRIC": {"FIRE": 1, "WATER": 2, "GRASS": 0.5, "ELECTRIC": 0.5},
}


# Class to define moves
class Move:
    def __init__(self, name, type, power):
        self.name = name
        self.type = type
        self.power = power

    def get_effectiveness_multiplier(self, target_pokemon):
        multiplier = 1
        for t in target_pokemon.types:
            multiplier *= TYPE_EFFECTIVENESS.get(self.type, {}).get(t, 1)
        return multiplier

# Class to define Pokémon
class Pokemon:
    def __init__(self, name, types, max_hp, attack, defense, moves):
        self.name = name
        self.types = types
        self.max_hp = max_hp
        self.current_hp = max_hp
        self.attack = attack
        self.defense = defense
        self.moves = moves
        self.is_fainted = False

    def take_damage(self, damage):
        self.current_hp -= damage
        if self.current_hp <= 0:
            self.current_hp = 0
            self.is_fainted = True
            print(f"{self.name} fainted!")
        else:
            print(f"{self.name} now has {self.current_hp}/{self.max_hp} HP.")

    def is_alive(self):
        return not self.is_fainted

    def display_status(self):
        print(f"--- {self.name} ---")
        print(f"HP: {self.current_hp}/{self.max_hp}")
        print(f"Type(s): {', '.join(self.types)}")

# Class to manage battles
class Battle:
    def __init__(self, trainer1, trainer2):
        self.trainer1 = trainer1
        self.trainer2 = trainer2

    def damage_calculation(self, attacking_pokemon, move, defending_pokemon):
        effectiveness = move.get_effectiveness_multiplier(defending_pokemon)
        damage = int(
            0.5 * (attacking_pokemon.attack / defending_pokemon.defense) * move.power * effectiveness
        )
        return damage, effectiveness

    def turn(self, attacking_pokemon, move, defending_pokemon):
        damage, effectiveness = self.damage_calculation(attacking_pokemon, move, defending_pokemon)

        print(f"{attacking_pokemon.name} used {move.name}!")
        if effectiveness > 1:
            print("It's super effective!")
        elif effectiveness < 1:
            print("It's not very effective...")

        defending_pokemon.take_damage(damage)

    def is_over(self):
        return not self.trainer1.has_active_pokemon() or not self.trainer2.has_active_pokemon()

    def get_winner(self):
        if not self.trainer1.has_active_pokemon():
            return self.trainer2
        elif not self.trainer2.has_active_pokemon():
            return self.trainer1
        return None

# Class to manage trainers and user interaction
class Trainer:
    def __init__(self, name, team):
        self.name = name
        self.team = team
        self.active_pokemon_index = 0

    def get_active_pokemon(self):
        return self.team[self.active_pokemon_index]

    def has_active_pokemon(self):
        return self.get_active_pokemon().is_alive()

    def choose_action(self):
        print("\nWhat will you do?")
        print("1. Fight")
        print("2. Switch Pokémon")
        while True:
            try:
                choice = int(input("> "))
                if choice in [1, 2]:
                    return choice
                else:
                    print("Invalid choice. Please enter 1 or 2.")
            except ValueError:
                print("Invalid input. Please enter a number.")

    def choose_move(self):
        active_pokemon = self.get_active_pokemon()
        print("\nChoose a move:")
        for i, move in enumerate(active_pokemon.moves):
            print(f"{i + 1}. {move.name}")
        while True:
            try:
                choice = int(input("> "))
                if 1 <= choice <= len(active_pokemon.moves):
                    return active_pokemon.moves[choice - 1]
                else:
                    print(f"Invalid choice. Please enter a number between 1 and {len(active_pokemon.moves)}.")
            except ValueError:
                print("Invalid input. Please enter a number.")

    def choose_pokemon_to_switch(self):
        print("\nSwitch to which Pokémon?")
        for i, pokemon in enumerate(self.team):
            if i != self.active_pokemon_index and pokemon.is_alive():
                print(f"{i + 1}. {pokemon.name} ({pokemon.current_hp}/{pokemon.max_hp})")
        while True:
            try:
                choice = int(input("> "))
                if 1 <= choice <= len(self.team) and self.team[choice - 1].is_alive():
                    self.active_pokemon_index = choice - 1
                    print(f"{self.name} switched to {self.get_active_pokemon().name}!")
                    break
                else:
                    print("Invalid choice. Please select a valid, non-fainted Pokémon.")
            except ValueError:
                print("Invalid input. Please enter a number.")

