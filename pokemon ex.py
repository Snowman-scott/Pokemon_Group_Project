# Function to get player's team
def get_player_team(available_pokemon):
    team = []
    print("\nSelect your team of 2 Pokémon:")
    for i, p in enumerate(available_pokemon):
        print(f"{i + 1}. {p.name}")

    while len(team) < 2:
        try:
            choice = int(input(f"Choose Pokémon #{len(team) + 1}: "))
            if 1 <= choice <= len(available_pokemon):
                pokemon = available_pokemon[choice - 1]
                if pokemon not in team:
                    team.append(pokemon)
                    print(f"{pokemon.name} added to your team!")
                else:
                    print("That Pokémon is already on your team.")
            else:
                print(f"Invalid choice. Please enter a number between 1 and {len(available_pokemon)}.")
        except ValueError:
                print("Invalid input. Please enter a number.")
    return team

# Main game loop
def main():
    available_pokemon = create_sample_data()

    player_name = input("Enter your name, Trainer: ")
    player_team = get_player_team(available_pokemon)
    player_trainer = Trainer(player_name, player_team)

    computer_team = [p for p in available_pokemon if p not in player_team]
    if not computer_team:
        computer_team = [random.choice(available_pokemon)]
    computer_trainer = Trainer("Computer", computer_team)

    print("\n" + "=" * 30)
    print("        A WILD BATTLE BEGINS!")
    print("=" * 30)

    battle = Battle(player_trainer, computer_trainer)

    while not battle.is_over():
        print("\n" + "-" * 30)
        player_trainer.get_active_pokemon().display_status()
        computer_trainer.get_active_pokemon().display_status()
        print("-" * 30)

        player_action = player_trainer.choose_action()
        if player_action == 1:
            player_move = player_trainer.choose_move()
            battle.turn(player_trainer.get_active_pokemon(), player_move, computer_trainer.get_active_pokemon())
        else:
            player_trainer.choose_pokemon_to_switch()

        if battle.is_over():
            break

        print("\nComputer's turn...")
        computer_move = random.choice(computer_trainer.get_active_pokemon().moves)
        battle.turn(computer_trainer.get_active_pokemon(), computer_move, player_trainer.get_active_pokemon())

        if not player_trainer.has_active_pokemon():
            if len([p for p in player_trainer.team if p.is_alive()]) > 0:
                print(f"{player_trainer.name}, your active Pokémon has fainted!")
                player_trainer.choose_pokemon_to_switch()
        if not computer_trainer.has_active_pokemon():
            if len([p for p in computer_trainer.team if p.is_alive()]) > 0:
                print(f"{computer_trainer.name}'s active Pokémon has fainted!")
                for i, p in enumerate(computer_trainer.team):
                    if p.is_alive():
                        computer_trainer.active_pokemon_index = i
                        print(f"Computer switched to {computer_trainer.get_active_pokemon().name}!")
                        break

    winner = battle.get_winner()
    if winner:
        print(f"\nCongratulations, {winner.name} wins the battle!")
    else:
        print("\nThe battle is a draw!")
